"""iptables and ip6tables read from iptables-save (the nf_tables variant's tables, and the legacy x_tables when the
kernel has them loaded), ebtables' and arptables' variants, and ipset's sets (`ipset list -t`): every rule as an
`Entry`, each chain's policy, whose each rule is (ufw's, Docker's, Kubernetes'... by its chain, the chain it jumps to,
an interface a program makes, a comment). The commands that change them are built here, never run."""
from __future__ import annotations

import re
import shlex
from dataclasses import dataclass, field

from liminal_libs.machines.firewall import PREFIX

from .model import Entry, digest, owner_by_interface, owner_by_name, ports_text, spans_of

BUILTIN = {"INPUT": "in", "OUTPUT": "out", "FORWARD": "fwd", "PREROUTING": "pre", "POSTROUTING": "post"}
TARGETS = {"ACCEPT": "accept", "DROP": "drop", "REJECT": "reject", "RETURN": "return", "LOG": "log", "NFLOG": "log",
           "ULOG": "log", "MASQUERADE": "nat", "SNAT": "nat", "DNAT": "nat", "REDIRECT": "nat", "NETMAP": "nat",
           "QUEUE": "queue", "NFQUEUE": "queue"}
VERSION = re.compile(r"v?(\d+(?:\.\d+)+)")
INCOMPATIBLE = re.compile(r"[Tt]able [`'\"]?(\w+)[`'\"]? is incompatible")
COMMENT_OWNERS = (("cali:", "calico"), ("kubernetes", "kubernetes"), ("KUBE", "kubernetes"), ("docker", "docker"),
                  ("cilium", "cilium"), ("flannel", "flannel"), ("tailscale", "tailscale"), ("netavark", "podman"))


def version_of(text: str) -> tuple[str, str]:
    """(version, variant) from `iptables -V` and its siblings: ("1.8.11", "nf_tables"), ("1.8.10", "legacy"), ("", "")."""
    t = (text or "").strip()
    if not t:
        return "", ""
    m = VERSION.search(t)
    version = m.group(1) if m else ""
    if "nf_tables" in t:
        return version, "nf_tables"
    if "legacy" in t:
        return version, "legacy"
    parts = tuple(int(x) for x in version.split(".")[:2]) if version else ()
    return version, ("legacy" if parts and parts < (1, 8) else "")  # before 1.8 there was no nf_tables variant


@dataclass(frozen=True)
class XChain:
    tool: str
    table: str
    name: str
    policy: str  # ACCEPT | DROP for a built-in chain; "-" for one of its own


@dataclass(frozen=True)
class XRule:
    tool: str
    table: str
    chain: str
    number: int  # its place in its chain, from 1
    args: tuple  # the words after -A CHAIN
    line: str


@dataclass
class Saved:
    """One iptables-save's answer: its tables' chains and rules."""

    tool: str  # iptables | ip6tables
    variant: str = ""  # nf_tables | legacy
    chains: list = field(default_factory=list)
    rules: list = field(default_factory=list)
    incompatible: list = field(default_factory=list)  # nftables tables iptables-nft cannot read (made with nft)
    header: str = ""

    @property
    def tables(self) -> list[str]:
        return list(dict.fromkeys([c.table for c in self.chains] + [r.table for r in self.rules]))


def parse_save(text: str, tool: str = "iptables", variant: str = "") -> Saved:
    out = Saved(tool, variant)
    table = ""
    counts: dict = {}
    for raw in (text or "").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            m = INCOMPATIBLE.search(line)
            if m:
                out.incompatible.append(m.group(1))
            if line.startswith("# Generated by") and not out.header:
                out.header = line
                if not out.variant:
                    out.variant = "nf_tables" if "nf_tables" in line else "legacy" if "legacy" in line else ""
            continue
        if line.startswith("*"):
            table = line[1:].strip()
            continue
        if line == "COMMIT":
            continue
        if line.startswith(":"):
            parts = line[1:].split()
            if parts:
                out.chains.append(XChain(tool, table, parts[0], parts[1] if len(parts) > 1 else "-"))
            continue
        if line.startswith("[") and "]" in line:  # counters of -c: [packets:bytes] -A ...
            line = line.split("]", 1)[1].strip()
        if line.startswith("-A "):
            try:
                words = shlex.split(line)
            except ValueError:
                words = line.split()
            if len(words) >= 2:
                chain = words[1]
                counts[(table, chain)] = counts.get((table, chain), 0) + 1
                out.rules.append(XRule(tool, table, chain, counts[(table, chain)], tuple(words[2:]), line))
    return out


def view(args, chains=frozenset()) -> dict:
    """The fields of a rule's words (its target, protocol, ports, addresses, interface, states, comment); `chains`: the
    table's own chains, which a -j jumps to."""
    out = {"action": "continue", "target": "", "protocol": "", "ports": "", "spans": (), "source": "", "destination": "",
           "interface": "", "state": "", "comment": "", "limited": False}
    words = list(args)
    i, neg = 0, ""
    while i < len(words):
        w = words[i]
        nxt = words[i + 1] if i + 1 < len(words) else ""
        if w == "!":
            neg = "not "
            i += 1
            continue
        took = 2
        if w in ("-p", "--protocol"):
            out["protocol"] = neg + nxt.lower()
        elif w in ("-s", "--source", "--src"):
            out["source"] = neg + nxt
        elif w in ("-d", "--destination", "--dst"):
            out["destination"] = neg + nxt
        elif w in ("-i", "--in-interface"):
            out["interface"] = neg + nxt
        elif w in ("-o", "--out-interface"):
            out["interface"] = out["interface"] or neg + nxt
        elif w in ("--dport", "--destination-port", "--dports", "--destination-ports"):
            spans = spans_of(nxt)
            out["ports"] = neg + (ports_text(spans) if spans else nxt)
            out["spans"] = () if neg else spans
        elif w == "--comment":
            out["comment"] = nxt
        elif w in ("--ctstate", "--state"):
            out["state"] = neg + nxt.lower()
        elif w in ("-j", "--jump"):
            if nxt in TARGETS:
                out["action"] = TARGETS[nxt]
                if out["action"] == "nat":
                    out["target"] = nxt
            elif nxt in chains:  # one of the table's own chains
                out["action"], out["target"] = "jump", nxt
            else:  # an extension's target that decides nothing (MARK, CT, TCPMSS...)
                out["action"], out["target"] = "continue", nxt
        elif w in ("-g", "--goto"):
            out["action"], out["target"] = "goto", nxt
        elif w in ("--to-destination", "--to-source", "--to-ports", "--to"):
            out["target"] = (out["target"] + " " + nxt).strip()
        elif w == "--limit":
            out["limited"] = True
        elif w in ("-m", "--match"):
            pass
        else:
            took = 1
        neg = ""
        i += took
    if out["action"] == "accept" and out.pop("limited"):
        out["action"] = "limit"
    out.pop("limited", None)
    return out


def reached(saved: Saved) -> dict:
    """The built-in chains each chain is reached from, through -j and -g: {(table, chain): {"INPUT", ...}}."""
    targets: dict = {}
    for r in saved.rules:
        args = list(r.args)
        for flag in ("-j", "--jump", "-g", "--goto"):
            if flag in args:
                k = args.index(flag)
                if k + 1 < len(args):
                    targets.setdefault((r.table, r.chain), set()).add((r.table, args[k + 1]))
    out: dict = {}
    for c in saved.chains:
        if c.name not in BUILTIN:
            continue
        todo, seen = [(c.table, c.name)], set()
        while todo:
            k = todo.pop()
            if k in seen:
                continue
            seen.add(k)
            out.setdefault(k, set()).add(c.name)
            todo.extend(targets.get(k, ()))
    return out


def direction_of(table: str, chains) -> str:
    names = set(chains)
    if table in ("filter", "security"):
        for c in ("INPUT", "OUTPUT", "FORWARD"):
            if c in names:
                return BUILTIN[c]
    if table == "nat":
        return "nat"
    return "other"


def rule_owner(r: XRule, v: dict) -> str:
    """Whose a rule is: Liminal's by its comment; a program's by its chain, the chain it jumps to, an interface it
    makes, a comment it writes; this machine's own otherwise."""
    if v["comment"].startswith(PREFIX + ":"):
        return "liminal"
    for name in (r.chain, v["target"]):
        o = owner_by_name(name or "")
        if o and o != "liminal":
            return o
    o = owner_by_interface(v["interface"])
    if o:
        return o
    for start, owner in COMMENT_OWNERS:
        if v["comment"].startswith(start) or start in v["comment"]:
            return owner
    return "own"


def _word(a: str) -> str:
    """A rule's word as iptables-save writes it: quoted only when it holds a space or a quote (a comment)."""
    return shlex.quote(a) if not a or re.search(r"[\s'\"\\]", a) else a


def entries(saved: Saved, binary: str = "") -> list[Entry]:
    """Every rule as an Entry. `binary`: the command that changes these rules (iptables-legacy for the legacy ones
    beside an nf_tables iptables), named in each one's ref."""
    hooks = reached(saved)
    out = []
    tool = binary or saved.tool
    family = "ipv6" if saved.tool == "ip6tables" else "ipv4"
    own_chains: dict = {}
    for c in saved.chains:
        if c.policy == "-":
            own_chains.setdefault(c.table, set()).add(c.name)
    for r in saved.rules:
        v = view(r.args, own_chains.get(r.table, frozenset()))
        direction = direction_of(r.table, hooks.get((r.table, r.chain), ())) if (r.table, r.chain) in hooks else "other"
        text = " ".join(_word(a) for a in r.args)
        out.append(Entry(ref=f"ipt|{tool}|{r.table}|{r.chain}|{r.number}|{digest(r.line)}", kind=saved.tool,
                         where=f"{r.table} {r.chain}" + (" (legacy)" if saved.variant == "legacy" and binary else ""),
                         direction=direction, action=v["action"], text=text, target=v["target"], protocol=v["protocol"],
                         ports=v["ports"], spans=v["spans"], source=v["source"], destination=v["destination"],
                         interface=v["interface"], state=v["state"], comment=v["comment"], owner=rule_owner(r, v),
                         family=family, number=r.number))
    return out


# -- ipset ------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
class IpSet:
    name: str
    type: str
    family: str = ""
    entries: int = 0
    references: int = 0


def parse_ipsets(text: str) -> list[IpSet]:
    """`ipset list -t` (the headers alone: no members listed)."""
    out, cur = [], {}

    def flush():
        if cur.get("Name"):
            header = cur.get("Header", "")
            fam = re.search(r"family (\w+)", header)
            out.append(IpSet(cur["Name"], cur.get("Type", ""), fam.group(1) if fam else "",
                             int(cur.get("Number of entries", "0") or 0) if str(cur.get("Number of entries", "0")).isdecimal() else 0,
                             int(cur.get("References", "0") or 0) if str(cur.get("References", "0")).isdecimal() else 0))

    for line in (text or "").splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            continue
        key = key.strip()
        if key == "Name":
            flush()
            cur = {}
        cur[key] = value.strip()
    flush()
    return out


# -- the commands that change them ----------------------------------------------------------------------------------
def rule_words(protocol: str, spans, source: str, interface: str, direction: str, comment: str) -> list[str]:
    words: list[str] = []
    if interface:
        words += ["-o" if direction == "out" else "-i", interface]
    if source:
        words += ["-d" if direction == "out" else "-s", source]
    if protocol in ("tcp", "udp"):
        words += ["-p", protocol]
        if spans:
            listed = ",".join(str(a) if a == b else f"{a}:{b}" for a, b in spans)
            words += ["-m", "multiport", "--dports", listed] if len(spans) > 1 else ["--dport", listed]
    words += ["-m", "comment", "--comment", comment]
    return words


def target_of(action: str) -> str:
    return {"allow": "ACCEPT", "block": "DROP", "reject": "REJECT"}[action]
